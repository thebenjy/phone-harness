#!/bin/bash
# One-time, per machine: make phone-harness available to Claude Code in every repo.
#
#   1. Installs the phone-harness CLI from this checkout as an editable uv tool
#      (git pull here = upgrade; re-run this script after a pull to refresh the skill).
#   2. Installs ~/.local/bin/phone-harness-mcp, the stdio launcher .mcp.json files point at.
#   3. Registers the phone-harness skill for Claude Code at ~/.claude/skills/phone-harness.
#
# Usage: integrations/claude-code/setup-host.sh
# Bash 3.2 compatible (macOS default shell).
set -eu

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
BIN_DIR="${HOME}/.local/bin"
SKILL_DIR="${HOME}/.claude/skills/phone-harness"
LAUNCHER="${BIN_DIR}/phone-harness-mcp"

if ! command -v uv >/dev/null 2>&1; then
    echo "uv is required: https://docs.astral.sh/uv/ (curl -LsSf https://astral.sh/uv/install.sh | sh)" >&2
    exit 1
fi

echo "==> Installing phone-harness CLI (editable) from ${REPO}"
uv tool install --python 3.12 --editable "${REPO}" --force

PH="${BIN_DIR}/phone-harness"
if [ ! -x "${PH}" ]; then
    PH="$(command -v phone-harness)"
fi

echo "==> Writing MCP launcher ${LAUNCHER}"
mkdir -p "${BIN_DIR}"
cat > "${LAUNCHER}" <<EOF
#!/bin/bash
# Generated by ${HERE}/setup-host.sh. Starts the phone-harness MCP server (stdio).
export PHONE_HARNESS_CLI="\${PHONE_HARNESS_CLI:-${PH}}"
exec uv run --quiet --script "${HERE}/mcp_server.py" "\$@"
EOF
chmod +x "${LAUNCHER}"

echo "==> Caching the MCP server's dependencies"
uv sync --quiet --script "${HERE}/mcp_server.py" || echo "    (skipped; the first launch will fetch them)"

echo "==> Registering the Claude Code skill at ${SKILL_DIR}"
mkdir -p "${SKILL_DIR}"
{
    "${PH}" skill
    cat <<'EOF'

## Claude Code

<!-- Appended by integrations/claude-code/setup-host.sh; re-run it after `phone-harness update`. -->

- When the `phone-harness` MCP server is connected, run scripts with
  `mcp__phone-harness__phone_exec` (same code as the heredoc form; a printed screenshot comes back
  as an image) and check the connection with `mcp__phone-harness__phone_doctor`. Otherwise use
  `phone-harness <<'PY' ... PY` in Bash and Read the screenshot path it prints.
- If the repo has `.claude/phone-app.md`, read it first: the app under test, its ids, and how to
  build and install it.
EOF
} > "${SKILL_DIR}/SKILL.md"

case ":${PATH}:" in
    *":${BIN_DIR}:"*) ;;
    *) echo "WARNING: ${BIN_DIR} is not on PATH; Claude Code will not find phone-harness-mcp." >&2 ;;
esac

echo
echo "Done. $("${PH}" --version)"
echo "Next: integrations/claude-code/add-to-repo.sh /path/to/app-repo --name \"My App\" ..."
echo "Check the phone: phone-harness doctor [ios|android]"
